#!/usr/bin/env python3
"""Promote only verified, committed public IoTKit CLI builds into the tap."""
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import quote
from urllib.request import Request, urlopen

ORIGIN = "https://api.iotkit.io"
ROOT = Path(__file__).resolve().parent.parent
TARGETS = {f"{system}-{arch}" for system in ("darwin", "linux", "windows") for arch in ("arm64", "amd64")}
HEX = re.compile(r"[a-f0-9]{64}")


def fetch(path, limit):
    request = Request(ORIGIN + path, headers={"User-Agent": "iotkit-homebrew-updater/1.0"})
    with urlopen(request, timeout=60) as response:
        data = response.read(limit + 1)
    if len(data) > limit:
        raise ValueError("Public download exceeds its admitted size")
    return data


def validate(release):
    if not isinstance(release, dict) or not HEX.fullmatch(str(release.get("id", ""))):
        raise ValueError("Invalid release identity")
    manifest, provenance = release["manifest"], release["provenance"]
    if manifest.get("schemaVersion") != 1 or manifest.get("name") != "iotk" or manifest.get("clean") is not True:
        raise ValueError("CLI build must be clean and versioned")
    version, revision = manifest.get("version", ""), manifest.get("revision", "")
    if not isinstance(version, str) or not re.fullmatch(r"[0-9A-Za-z][0-9A-Za-z.+_-]{0,79}", version):
        raise ValueError("Invalid upstream version")
    if not isinstance(revision, str) or not re.fullmatch(r"[a-f0-9]{40}", revision):
        raise ValueError("Invalid source revision")
    number = provenance.get("buildRunNumber")
    if provenance.get("repository") != "boatkit-io/iotkit" or type(number) is not int or number < 1:
        raise ValueError("Invalid upstream build provenance")
    artifacts = manifest.get("artifacts", [])
    if len(artifacts) != 6 or {a.get("target") for a in artifacts} != TARGETS:
        raise ValueError("Incomplete CLI target matrix")
    for artifact in artifacts:
        extension = "zip" if artifact["target"].startswith("windows-") else "tar.gz"
        expected = f"iotk-{version}-{artifact['target']}.{extension}"
        if artifact.get("file") != expected or type(artifact.get("size")) is not int or not 0 < artifact["size"] <= 32 * 1024**2:
            raise ValueError("Invalid archive identity or size")
        for key in ("sha256", "binarySha256"):
            if not isinstance(artifact.get(key), str) or not HEX.fullmatch(artifact[key]):
                raise ValueError("Invalid archive checksum")
    return release


def package_version(release):
    version = release["manifest"]["version"].removeprefix("v")
    if re.fullmatch(r"\d+\.\d+\.\d+", version):
        return version
    if not version.startswith("0.0.0-dev."):
        raise ValueError("Define Homebrew version ordering for this upstream release channel")
    # Upstream development versions contain a hash, which does not order upgrades.
    return f"0.0.0-dev.{release['provenance']['buildRunNumber']}"


def cask(release):
    validate(release)
    manifest = release["manifest"]
    lines = [
        "# Generated by scripts/update.py from a verified upstream publication.",
        'cask "iotk" do',
        '  name "IoTKit CLI"',
        '  desc "Provision and manage IoTKit devices"',
        '  homepage "https://iotkit.io"',
        f'  version "{package_version(release)}"',
        "",
    ]
    for system, block in (("darwin", "on_macos"), ("linux", "on_linux")):
        lines.append(f"  {block} do")
        for arch, arch_block in (("arm64", "on_arm"), ("amd64", "on_intel")):
            artifact = next(a for a in manifest["artifacts"] if a["target"] == f"{system}-{arch}")
            path = f"/v1/cli-downloads/{release['id']}/{quote(artifact['file'], safe='')}"
            lines.extend([
                f"    {arch_block} do",
                f'      url "{ORIGIN}{path}"',
                f'      sha256 "{artifact["sha256"]}"',
                "    end",
            ])
        lines.extend(["  end", ""])
    lines.extend([
        '  binary "iotk"',
        "end",
        "",
    ])
    return "\n".join(lines)


def update(root=ROOT, read=fetch):
    release = json.loads(read("/v1/cli-releases", 32768))["latest"]
    if release is None:
        raise ValueError("No committed upstream CLI build is available")
    validate(release)
    generated = cask(release)
    record = root / "release.json"
    if record.exists():
        previous = validate(json.loads(record.read_text()))
        old, new = previous["provenance"]["buildRunNumber"], release["provenance"]["buildRunNumber"]
        if new < old:
            raise ValueError("Refusing to downgrade to an older upstream build")
        if new == old and previous["id"] != release["id"]:
            raise ValueError("An upstream build number cannot replace its immutable bytes")
        if previous == release and (root / "Casks/iotk.rb").exists() and (root / "Casks/iotk.rb").read_text() == generated:
            print("Tap already references the latest verified build")
            return False
    prefix = f"/v1/cli-downloads/{release['id']}/"
    raw = read(prefix + "manifest.json", 16384)
    if hashlib.sha256(raw).hexdigest() != release["id"] or json.loads(raw) != release["manifest"]:
        raise ValueError("Published manifest bytes differ from the catalog")
    for artifact in release["manifest"]["artifacts"]:
        if artifact["target"].startswith("windows-"):
            continue
        data = read(prefix + quote(artifact["file"], safe=""), artifact["size"])
        if len(data) != artifact["size"] or hashlib.sha256(data).hexdigest() != artifact["sha256"]:
            raise ValueError("Published archive bytes differ from the manifest")
    (root / "Casks").mkdir(exist_ok=True)
    (root / "Casks/iotk.rb").write_text(generated)
    record.write_text(json.dumps(release, indent=2) + "\n")
    print(f"Verified Homebrew {package_version(release)} at source {release['manifest']['revision']}")
    return True


if __name__ == "__main__":
    update()
